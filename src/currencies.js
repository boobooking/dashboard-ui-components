// null и undefined — весь список; не массив — пустой. Иначе записи по кодам в
// порядке массива, без повторов; неизвестные коды пропускаются, регистр значим.
export function pickCurrencies(codes) {
    if (codes === null || codes === undefined) {
        return CURRENCIES
    }

    if (!Array.isArray(codes)) {
        return []
    }

    const picked = []

    for (const code of codes) {
        const currency = CURRENCIES.find((item) => item.code === code)

        if (currency && !picked.includes(currency)) {
            picked.push(currency)
        }
    }

    return picked
}

// Подпись валюты: символ с кодом, а если символа нет — один код.
export function currencyLabel(currency) {
    return currency.symbol === null ? currency.code : `${currency.code} ${currency.symbol}`
}
